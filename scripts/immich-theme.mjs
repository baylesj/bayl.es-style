// Generates immich/bayles.css, custom CSS for Immich (Administration > Settings > Theme > Custom CSS), from the
// color tokens in src/tokens.css, so the photo library matches the sites. Run by `npm run build`.
// Immich v3 themes through CSS variables: --immich-{primary,bg,fg,gray} (+ dark-*) as "r g b" triplets, an
// --immich-ui-primary-50..950 scale (inverted under .dark), the Tailwind --color-neutral-* ramp its grays are
// built from, the page/text/panel bases --immich-ui-{light,dark,gray}, and --font-sans.
import { readFileSync, writeFileSync } from "node:fs";

const css = readFileSync(new URL("../src/tokens.css", import.meta.url), "utf8");
const tokens = {};
for (const [, name, light, dark] of css.matchAll(
  /--([\w-]+):\s*light-dark\((#[0-9a-f]{3,6}),\s*(#[0-9a-f]{3,6})\)/gi,
)) {
  tokens[name] = { light: expand(light), dark: expand(dark) };
}

function expand(hex) {
  const h = hex.slice(1).toLowerCase();
  return "#" + (h.length === 3 ? [...h].map((c) => c + c).join("") : h);
}
const t = (name, m) => {
  if (!tokens[name]) throw new Error(`missing token --${name}`);
  return tokens[name][m];
};
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
const mix = (a, b, w) =>
  "#" +
  rgb(a)
    .map((v, i) =>
      Math.round(v * w + rgb(b)[i] * (1 - w))
        .toString(16)
        .padStart(2, "0"),
    )
    .join("");
const triplet = (hex) => rgb(hex).join(" ");

const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
// Light: 50..400 lean to white, 500 is the color, 600..950 lean to the dark ground.
const LIGHT_W = [0.06, 0.12, 0.25, 0.45, 0.7, 1, 0.85, 0.7, 0.55, 0.42, 0.3];
// Dark (Immich inverts the scale): 50..400 lean to the dark ground, 500 is the color, 600..950 lean to white.
const DARK_W = [0.1, 0.18, 0.3, 0.42, 0.55, 1, 0.8, 0.6, 0.42, 0.25, 0.12];
const scale = (color, toward, w, beyond) =>
  STEPS.map((s, i) => [
    s,
    i < 5 ? mix(color, toward, w[i]) : i === 5 ? color : mix(color, beyond, w[i]),
  ]);

const teal = { light: t("teal", "light"), dark: t("teal", "dark") };
const ground = { light: t("ground", "light"), dark: t("ground", "dark") };
const ink = { light: t("ink", "light"), dark: t("ink", "dark") };
const field = { light: t("field", "light"), dark: t("field", "dark") };

const primaryLight = scale(teal.light, "#ffffff", LIGHT_W, ground.dark);
const primaryDark = scale(teal.dark, ground.dark, DARK_W, "#ffffff");
// Teal-tinted neutrals from the light page to the dark page (Tailwind's ramp shape).
const NEUTRAL_W = [1, 0.96, 0.89, 0.8, 0.6, 0.43, 0.31, 0.23, 0.13, 0.06, 0];
const neutral = STEPS.map((s, i) => [s, mix(ground.light, ground.dark, NEUTRAL_W[i])]);

const vars = (pairs, prefix) => pairs.map(([s, c]) => `  ${prefix}-${s}: ${c};`).join("\n");
const FONT = "https://cdn.jsdelivr.net/npm/@fontsource-variable/schibsted-grotesk@5.2.8/files";

const out = `/* Generated by scripts/immich-theme.mjs from src/tokens.css (bayl.es-style). Don't edit by hand.
 * Paste into Immich: Administration > Settings > Theme > Custom CSS (eopsin's theme-sync.sh does it). */
@font-face {
  font-family: "Schibsted Grotesk";
  font-style: normal;
  font-weight: 400 900;
  font-display: swap;
  src: url("${FONT}/schibsted-grotesk-latin-wght-normal.woff2") format("woff2");
}
:root {
  --font-sans: "Schibsted Grotesk", -apple-system, system-ui, sans-serif;
  --immich-primary: ${triplet(teal.light)};
  --immich-dark-primary: ${triplet(teal.dark)};
  --immich-bg: ${triplet(ground.light)};
  --immich-dark-bg: ${triplet(ground.dark)};
  --immich-fg: ${triplet(ink.light)};
  --immich-dark-fg: ${triplet(ink.dark)};
  --immich-gray: ${triplet(mix(ink.light, ground.light, 0.05))};
  --immich-dark-gray: ${triplet(field.dark)};
${vars(primaryLight, "--immich-ui-primary")}
  --immich-ui-light: ${ground.light};
  --immich-ui-dark: ${ink.light};
  --immich-ui-gray: ${mix(ink.light, ground.light, 0.05)};
${vars(neutral, "--color-neutral")}
}
:root.dark,
.dark {
  --immich-ui-light: ${ground.dark};
  --immich-ui-dark: ${ink.dark};
  --immich-ui-gray: ${field.dark};
${vars(primaryDark, "--immich-ui-primary")}
}
`;
writeFileSync(new URL("../immich/bayles.css", import.meta.url), out);
console.log("immich/bayles.css");
