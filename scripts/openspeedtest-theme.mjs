// Generates openspeedtest/bayles.css, a theme for OpenSpeedTest (the self-hosted speed test), from the color tokens
// in src/tokens.css. Run by `npm run build`. OpenSpeedTest inlines its SVG UI into the page and colors it from
// app.css classes (and darkmode.css in dark mode), so later rules with the same selectors win; the gauge gradient
// is two <stop> elements whose stop-color CSS overrides. Uses the "home" signature (teal into green).
import { readFileSync, writeFileSync } from "node:fs";

const css = readFileSync(new URL("../src/tokens.css", import.meta.url), "utf8");
const tokens = {};
for (const [, name, light, dark] of css.matchAll(
  /--([\w-]+):\s*light-dark\((#[0-9a-f]{3,6}),\s*(#[0-9a-f]{3,6})\)/gi,
)) {
  tokens[name] = { light: expand(light), dark: expand(dark) };
}

function expand(hex) {
  const h = hex.slice(1).toLowerCase();
  return "#" + (h.length === 3 ? [...h].map((c) => c + c).join("") : h);
}
const t = (name, m) => {
  if (!tokens[name]) throw new Error(`missing token --${name}`);
  return tokens[name][m];
};
const rgb = (hex) => [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
const mix = (a, b, w) =>
  "#" +
  rgb(a)
    .map((v, i) =>
      Math.round(v * w + rgb(b)[i] * (1 - w))
        .toString(16)
        .padStart(2, "0"),
    )
    .join("");

// Panel tint: the ink 4% over the page in light mode; the form-field color in dark.
const vars = (m) => `
  --ost-ink: ${t("ink", m)};
  --ost-comment: ${t("comment", m)};
  --ost-line: ${t("line", m)};
  --ost-ground: ${t("ground", m)};
  --ost-panel: ${m === "light" ? mix(t("ink", m), t("ground", m), 0.04) : t("field", m)};
  --ost-teal: ${t("teal", m)};
  --ost-sig: ${t("teal-bright", m)};
  --ost-sig2: ${t("green-bright", m)};
  --ost-on-sig: ${t("on-sig", m)};`;

